#!/usr/bin/env python3
"""Push labeled sets and results to the orphan branch `data` of this repo (and pull what other machines pushed).

  sync_data.py [--quiet]

Layout on `data`:  sets/<name>/{commits/*.patch, answers.json, tests.json, DONE}   results/results-<host>.jsonl
                   results/rival-notes-<host>.jsonl   results/REPORT.md   results/status-<host>.txt
Each machine only writes its own results-<host>.jsonl, so two machines never conflict. The working copy in
$VCV_DATA/data-repo is always reset to origin/data first and our files are copied on top (nothing lives only there),
then commit + push; a rejected push is retried from the fetch (that is the pull-rebase, without conflicts).
Push credentials are whatever `git push` of this repo already uses (gh auth login).
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import vcv  # noqa: E402

DATA = vcv.DATA
WC = DATA / "data-repo"
SETS = ["dev300", "hold300", "odd200", "traps150"]
Q = "--quiet" in sys.argv


def git(*a, check=True, cwd=None):
    return subprocess.run(["git", *a], cwd=cwd or WC, capture_output=True, text=True, check=check)


def log(msg):
    if not Q:
        print(f"[sync] {msg}", flush=True)


def ensure_clone():
    if (WC / ".git").exists():
        return
    url = subprocess.run(["git", "-C", str(vcv.REPO), "remote", "get-url", "origin"], capture_output=True, text=True,
                         check=True).stdout.strip()
    WC.mkdir(parents=True, exist_ok=True)
    git("init", "-q", "-b", "data", cwd=WC)
    git("remote", "add", "origin", url)
    git("config", "user.email", "bench@localhost")
    git("config", "user.name", f"bench-{vcv.HOST}")


def reset_to_remote():
    r = git("fetch", "-q", "origin", "data", check=False)
    if r.returncode == 0:
        git("checkout", "-q", "-B", "data", "origin/data")
        git("reset", "-q", "--hard", "origin/data")
        git("clean", "-fdq")
        return True
    return False  # branch does not exist yet: we create it


def copy_sets():
    for name in SETS:
        src = DATA / name
        ans = src / "answers.json"
        if not ans.exists():
            continue
        commits = json.loads(ans.read_text())["commits"]
        dst = WC / "sets" / name
        (dst / "commits").mkdir(parents=True, exist_ok=True)
        for p in (dst / "commits").glob("*.patch"):
            if p.stem not in commits:
                p.unlink()
        for cid in commits:
            s, d = src / "commits" / f"{cid}.patch", dst / "commits" / f"{cid}.patch"
            if s.exists() and (not d.exists() or d.read_bytes() != s.read_bytes()):
                shutil.copyfile(s, d)
        for f in ("answers.json", "tests.json"):
            if (src / f).exists():
                shutil.copyfile(src / f, dst / f)
        done = dst / "DONE"
        if (src / "DONE").exists():
            shutil.copyfile(src / "DONE", done)
        elif done.exists():
            done.unlink()


def copy_results():
    res = WC / "results"
    res.mkdir(parents=True, exist_ok=True)
    for src, dst in ((DATA / "results.jsonl", f"results-{vcv.HOST}.jsonl"),
                     (DATA / "rival-notes.jsonl", f"rival-notes-{vcv.HOST}.jsonl")):
        if src.exists():
            shutil.copyfile(src, res / dst)
    st = DATA / "status.txt"
    if st.exists():
        shutil.copyfile(st, res / f"status-{vcv.HOST}.txt")
    (WC / "README.md").write_text("Data branch (generated by bench/sync_data.py). sets/<name>: labeled patch sets; "
                                  "results/: scores, REPORT.md. Do not edit by hand.\n")
    subprocess.run([sys.executable, str(HERE / "report.py"), "--out", str(res / "REPORT.md")], check=False,
                   capture_output=True)


def main():
    ensure_clone()
    for attempt in range(6):
        have_remote = reset_to_remote()
        copy_sets()
        copy_results()
        git("add", "-A")
        if git("status", "--porcelain").stdout.strip() == "":
            log("nothing new")
            (DATA / "last_push").write_text(time.strftime("%F %T") + " (nothing new)\n")
            return 0
        git("commit", "-q", "-m", f"data: {vcv.HOST} {time.strftime('%F %T')}")
        p = git("push", "-q", "origin", "HEAD:data", check=False)
        if p.returncode == 0:
            log("pushed")
            (DATA / "last_push").write_text(time.strftime("%F %T") + "\n")
            return 0
        log(f"push rejected, retrying ({p.stderr.strip()[-120:]})")
        (DATA / "last_error").write_text(f"{time.strftime('%F %T')} sync: push failed: {p.stderr.strip()[-200:]}\n")
        time.sleep(3 + attempt * 5)
    return 1


if __name__ == "__main__":
    sys.exit(main())
